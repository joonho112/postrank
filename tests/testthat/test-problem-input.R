testthat::test_that("problem validates grade limits and preserves source identity",{
  p<-postrank_pairwise(pr_test_payload());w<-c(need1=.5,need2=.5)
  for(G in list(0,1.5,4,Inf,TRUE,1+1i,matrix(1)))testthat::expect_error(postrank_problem(p,w,.25,G),class="postrank_input_error")
  problem<-postrank_problem(p,w,.25,1)
  testthat::expect_equal(length(problem$index$labels),3)
  testthat::expect_equal(length(problem$index$pairs),6)
  testthat::expect_equal(dim(problem$model$A),c(12,9))
  testthat::expect_identical(problem$input_identity,p$input_identity)
  problem$model$objective[1]<-1
  testthat::expect_error(.pr_validate_problem(problem),"changed after construction")
})
testthat::test_that("optional settings validate explicit domains and combinations",{
  p<-postrank_pairwise(pr_test_payload());w<-c(need1=.5,need2=.5)
  for(q in list(numeric(),c(.1),c(need1=NA),c(need1=-.1),c(need1=1.1),c(nope=.1),c(need1=.1,need1=.2),matrix(.1)))
    testthat::expect_error(postrank_problem(p,w,.25,3,q=q),class="postrank_input_error")
  for(G in list(0,1.5,4,Inf,TRUE,matrix(1)))
    testthat::expect_error(postrank_problem(p,w,.25,3,exact_G=G),class="postrank_input_error")
  for(k in list(character(),"nope",c("need1","need1"),NA_character_))
    testthat::expect_error(postrank_problem(p,w,.25,3,objective="minimax",minimax_criteria=k),class="postrank_input_error")
  testthat::expect_error(postrank_problem(p,w,.25,3,minimax_criteria="need1"),class="postrank_input_error")
  pr<-postrank_problem(p,w,.25,3,objective="minimax",q=c(need2=.2),exact_G=2,minimax_criteria="need1")
  testthat::expect_equal(pr$objective_units,list(raw="minimax_risk_t",scale=1,offset=0))
  testthat::expect_equal(pr$model$var_upper[pr$index$labels],rep(2,3))
})
testthat::test_that("unknown or invalid solver controls never silently apply",{
  for(control in list(list(magic=1),list(time_limit=0),list(threads=0),list(seed=-1),list(absolute_risk_gap=-1),list(relative_gap=Inf),list(output=1)))
    testthat::expect_error(.pr_control(control),class="postrank_input_error")
  c<-.pr_control(list(time_limit=3,threads=1,absolute_risk_gap=.001))
  testthat::expect_identical(c$time_limit,3);testthat::expect_identical(c$relative_gap,0)
})
