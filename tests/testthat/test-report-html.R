# T-ux-09/10/12/13/16: the standalone English HTML report embeds only the eligible shipped
# figures from prepared objects, never overwrites, and keeps its honesty footer.
pr_html_of <- function(path) paste(readLines(path, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
pr_n_png <- function(html) lengths(regmatches(html, gregexpr("data:image/png;base64,", html, fixed = TRUE)))
pr_fig_state <- function(rep) vapply(rep$figures, function(f) if (isTRUE(f$available)) "embedded" else f$reason, "")

test_that("a complete analysis embeds the report card and the criterion profile (2)", {
  skip_if_not(isTRUE(capabilities("png")), "no PNG device")
  a <- pr_cached("analysis_30x3_tau35"); path <- withr::local_tempfile(fileext = ".html")
  rep <- postrank_report(a$fit, analysis = a, output_file = path)
  expect_identical(pr_fig_state(rep), c("embedded", "embedded"))
  expect_identical(vapply(rep$figures, `[[`, "", "id"), c("fig-report-card", "fig-criterion-profile"))
  html <- pr_html_of(path)
  expect_identical(pr_n_png(html), 2L)
  expect_false(grepl("(src|href)=\"(?!data:)", html, perl = TRUE))
  expect_false(grepl("https?://", gsub("data:image/png;base64,[A-Za-z0-9+/=]+", "", html)))
  ids <- regmatches(html, gregexpr("<(section|header) id=\"[a-z]+\"", html))[[1]]
  expect_identical(sub(".*id=\"([a-z]+)\"", "\\1", ids), rep$sections)
  expect_length(rep$sections, 11L)
  expect_match(html, "<html lang=\"en\">", fixed = TRUE)
  expect_match(html, "One validated incumbent is shown; the number of optima is unknown.", fixed = TRUE)
  expect_match(html, "Numerical certification: false.", fixed = TRUE)
  expect_match(html, "not independent verification", fixed = TRUE)
  expect_identical(rep$strings_version, "postrank-report-en-4")
  expect_match(paste(format(rep), collapse = "\n"), "11 sections; 2 available figures", fixed = TRUE)
  # Authored text passes the contextual wording guard (stored evidence is not scanned).
  authored <- gsub("<pre>.*?</pre>|<table>.*?</table>|data:image[^\"]+", " ", html, perl = TRUE)
  expect_identical(.pr_cli_guard(gsub("<[^>]+>", " ", authored)), character())
})

