  expect_identical(grep_card$report_card, g$report_card)
})

test_that("the report never recomputes: no solve, pairing, evaluation, card or summaries (T-ux-16)", {
  a <- pr_cached("analysis_30x3_tau35")
  boom <- function(...) stop("recomputation attempted")
  local_mocked_bindings(.pr_solve_core = boom, postrank_pairwise = boom, postrank_evaluate = boom,
    postrank_report_card = boom, .pr_posterior_summaries = boom)
  rep <- expect_no_error(postrank_report(a$fit, analysis = a, figures = isTRUE(capabilities("png"))))
  expect_identical(rep$input_identity, a$fit$input_identity)
  expect_identical(rep$solution_identity, a$fit$solution_identity)
})

