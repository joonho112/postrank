test_that("figures = FALSE, no incumbent and device failure embed nothing and stay valid (0)", {
  a <- pr_cached("analysis_30x3_tau35")
  off <- postrank_report(a$fit, analysis = a, figures = FALSE)
  expect_identical(pr_fig_state(off), c("figures_disabled", "figures_disabled"))
  x <- postrank_problem(postrank_pairwise(postrank_toy), c(need_A = .6, need_B = .4), .25, 3L)
  local_mocked_bindings(.pr_solve_core = pr_mock_solver(grade = NULL, status = "time_limit", lower = .1))
  none <- postrank_solve(x, backend = "highs")
  expect_false(none$incumbent_validated)
  path <- withr::local_tempfile(fileext = ".html")
  rep <- postrank_report(none, output_file = path)
  expect_identical(pr_fig_state(rep), c("no_validated_incumbent", "no_validated_incumbent"))
  html <- pr_html_of(path)
  expect_identical(pr_n_png(html), 0L)
  expect_match(html, "No validated incumbent is available; no grade is reported. Numerical certification: false.", fixed = TRUE)
  expect_false(grepl("One validated incumbent is shown", html, fixed = TRUE))
  local_mocked_bindings(ggsave = function(...) stop("device broke"), .package = "ggplot2")
  broken <- postrank_report(a$fit, analysis = a, output_file = withr::local_tempfile(fileext = ".html"))
  expect_identical(pr_fig_state(broken), c("device_unavailable", "device_unavailable"))
  expect_match(broken$figures[[1]]$detail, "device broke", fixed = TRUE)
  expect_true(file.exists(broken$output_file))
})

test_that("an existing output file is never overwritten (T-ux-10)", {
  a <- pr_cached("toy_analysis"); path <- withr::local_tempfile(fileext = ".html")
  postrank_report(a$fit, analysis = a, output_file = path, figures = FALSE)
  before <- unname(tools::md5sum(path))
  e <- tryCatch(postrank_report(a$fit, analysis = a, output_file = path), error = identity)
  expect_s3_class(e, "postrank_input_error"); expect_identical(e$code, "report_exists")
  expect_identical(unname(tools::md5sum(path)), before)
  e <- tryCatch(postrank_report(a$fit, output_file = withr::local_tempfile(fileext = ".txt")), error = identity)
  expect_identical(e$code, "invalid_report_path")
})

