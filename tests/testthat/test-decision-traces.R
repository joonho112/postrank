testthat::test_that("decision traces use literal same-state loss, q margins and explicit pairs",{
  d<-as_postrank_draws(pr_test_payload());g<-stats::setNames(c(1,2,2),d$entity_ids)
  settings<-list(weights=c(need1=.6,need2=.4),tau=.25,q=c(need2=.2),objective="weighted")
  pairs<-list(list(entity_i="001",entity_j="002",criterion_id="need1"))
  t<-.pr_decision_traces(d,g,settings,pairs,TRUE)
  values<-d$joint_draws$tensor$values;D<-matrix(0,4,2)
  for(s in 1:4)for(k in 1:2)D[s,k]<-as.numeric(values[s,1,k]<=values[s,2,k])+as.numeric(values[s,1,k]<=values[s,3,k])
  testthat::expect_equal(t$criterion_error_1$values,D[,1]/3)
  testthat::expect_equal(t$criterion_risk_2$values,(D[,2]+.25)/3)
  testthat::expect_equal(t$protection_margin_2$values,D[,2]-.4)
  testthat::expect_equal(t$weighted_total_loss$values,(.6*D[,1]+.4*D[,2]+.25)/3)
  testthat::expect_equal(t$pair_1$values,as.numeric(values[,1,1]<=values[,2,1]))
  testthat::expect_true(t$weighted_total_loss$post_selection_descriptive)
  testthat::expect_null(t$weighted_total_loss$criterion_id)
  testthat::expect_length(.pr_diagnostic_pairs(NULL,d),0)
  testthat::expect_error(.pr_diagnostic_pairs(list(pairs[[1]],pairs[[1]]),d),"duplicate")
  testthat::expect_error(.pr_diagnostic_pairs(list(pairs[[1]],pairs[[1]][c(3,2,1)]),d),"duplicate")
})
testthat::test_that("criterionwise traces never synthesize a total trace and all-tie margins stay zero",{
  d<-as_postrank_draws(pr_test_criterionwise());g<-stats::setNames(rep(1,3),d$entity_ids)
  settings<-list(weights=c(need1=.5,need2=.5),tau=.25,q=c(need1=0),objective="weighted")
  t<-.pr_decision_traces(d,g,settings,list())
  testthat::expect_equal(length(t$criterion_error_1$values),4)
  testthat::expect_equal(length(t$criterion_error_2$values),5)
  testthat::expect_null(t$weighted_total_loss)
  testthat::expect_equal(t$criterion_error_1$values,rep(0,4))
  testthat::expect_equal(t$criterion_risk_2$values,rep(.25,5))
  testthat::expect_equal(t$protection_margin_1$values,rep(0,4))
})
testthat::test_that("finite laws keep state masses and posterior profiles preserve target coordinates",{
  d<-as_postrank_draws(pr_test_exact());g<-stats::setNames(c(1,2,2),d$entity_ids)
  settings<-list(weights=c(need1=.5,need2=.5),tau=.25,q=NULL,objective="weighted")
  t<-.pr_decision_traces(d,g,settings,list())
  testthat::expect_equal(t$weighted_total_loss$exact_weights,c(2/3,1/3))
  testthat::expect_identical(t$weighted_total_loss$sampling$regime,"exact_law")
  testthat::expect_equal(t$weighted_total_loss$mean_override,sum(c(2/3,1/3)*t$weighted_total_loss$values))
  p<-.pr_posterior_profiles(d)
  testthat::expect_equal(nrow(p),6)
  testthat::expect_equal(p$mean[1],8/3)
  testthat::expect_equal(p$median[1],3)
  testthat::expect_equal(p$lower_95[1],2)
})
