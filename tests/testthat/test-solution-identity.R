testthat::test_that("relation identity ignores label spacing and entity storage order",{
  a<-.pr_solution_identity(c(A=1,B=3,C=3),c("A","B","C"))
  b<-.pr_solution_identity(c(C=8,A=2,B=8),c("C","A","B"))
  testthat::expect_identical(a$relation_identity,b$relation_identity)
  testthat::expect_false(a$primary_objective_perturbed)
  testthat::expect_false(a$deterministic_representative)
  testthat::expect_identical(a$representative_policy,"one_validated_incumbent")
  c<-.pr_solution_identity(c(A=2,B=1,C=1),c("A","B","C"))
  testthat::expect_false(identical(a$relation_identity,c$relation_identity))
})
testthat::test_that("minimax evaluates maximum expected criterion risk with weighted auxiliary",{
  p<-postrank_pairwise(pr_test_payload());w<-c(need1=1,need2=0)
  e<-postrank_evaluate(stats::setNames(c(1,2,2),p$entity_ids),p,w,.25,"minimax")
  testthat::expect_equal(e$primary_risk,max(e$criterion_risk))
  testthat::expect_equal(e$weighted_risk,e$criterion_risk['need1'],ignore_attr=TRUE)
  a<-postrank_evaluate(stats::setNames(c(1,1,1),p$entity_ids),p,w,.25,"minimax")
  testthat::expect_equal(a$primary_risk,.25)
  testthat::expect_true(all(is.na(a$E_over_N)))
})
